export function getColorIconSymbol(colorData) {
  if (!colorData || colorData.isNone) return 'a_ColorIcon_None';
  if (colorData.schemeId && COLOR_SCHEME_ICON_MAP[colorData.schemeId]) {
    return COLOR_SCHEME_ICON_MAP[colorData.schemeId];
  }
  const name = String(colorData.schemeName || colorData.displayName || '').replace(/[\s\-_]/g, '').toLowerCase();
  if (COLOR_NAME_ICON_MAP[name]) {
    return COLOR_NAME_ICON_MAP[name];
  }
  return 'a_ColorIcon_' + (colorData.schemeName || 'None');
}

